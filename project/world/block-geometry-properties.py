"""Generate the browser connection traits from the reference BlockRegistry probe."""

import argparse
import csv
from pathlib import Path


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("registry", type=Path)
    parser.add_argument("output", type=Path, nargs="?",
                        default=Path(__file__).with_suffix(".mjs"))
    args = parser.parse_args()

    with args.registry.open(encoding="utf-8-sig", newline="") as registry:
        blocks = sorted(csv.DictReader(registry, delimiter="\t"), key=lambda block: int(block["id"]))

    lines = ["// Generated by block-geometry-properties.py using the original Forge registry."]
    for name, trait in (("fenceCubes", "fenceCube"), ("paneOpaqueBlocks", "opaque")):
        ids = [block["id"] for block in blocks if block[trait] == "true"]
        lines.append(f"export const {name} = new Set([")
        for start in range(0, len(ids), 18):
            lines.append(f"  {', '.join(ids[start:start + 18])},")
        lines.append("]);")
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
