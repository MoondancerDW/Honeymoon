const removedDecor=/^legacy:(?:6|31|32|37|38|39|40|50|51|55|59|75|76|78|106):/;
const bridges=/^legacy:(?:1|4|44|98):/;
const water=/^legacy:[89]:/;

function geometry(base,{x,z,width,length,bottom,top,step,crossing}) {
  const blocks=new Map();
  const palette=new Map();
  const keyAt=(x,y,z)=>`${x},${y},${z}`;
  function colorOf(name) {
    if (!palette.has(name)) {
      const faces=shapeFor(name);
      const face=faces.find(shape=>shape.faces?.some(tile=>tile>=0));
      palette.set(name,face ? [face.faces[3]>=0 ? face.faces[3] : face.faces.find(tile=>tile>=0),face.tint ?? 0xffffff] : null);
    }
    return palette.get(name);
  }
  for (let by=bottom;by<=top;by+=step) for (let bz=z-length;bz<=z+length;bz+=step) {
    for (let bx=x-width;bx<=x+width;bx+=step) {
      const dx=Math.min(step,x+width+1-bx),dy=Math.min(step,top+1-by),dz=Math.min(step,z+length+1-bz);
      const choices=new Map();
      let count=0;
      for (let iy=0;iy<dy;iy++) for (let iz=0;iz<dz;iz++) for (let ix=0;ix<dx;ix++) {
        const xx=bx+ix,yy=by+iy,zz=bz+iz;
        const {key}=base.getCell(xx,yy,zz);
        if (key==='air' || removedDecor.test(key) || water.test(key)) continue;
        if (crossing && (!bridges.test(key) || base.getCell(xx,65,zz).key!=='air' || !water.test(base.getCell(xx,64,zz).key))) continue;
        choices.set(key,1+(choices.get(key) ?? 0));
        count++;
      }
      if (!count) continue;
      const selected=[...choices].sort((left,right)=>right[1]-left[1]).find(([name])=>colorOf(name));
      if (!selected) continue;
      blocks.set(keyAt(bx,by,bz),[bx,by,bz,dx,dy,dz,...colorOf(selected[0])]);
    }
  }
  return [...blocks.values()].filter(([x,y,z])=>crossing || ![
    [x-step,y,z],[x+step,y,z],[x,y-step,z],[x,y+step,z],[x,y,z-step],[x,y,z+step],
  ].every(point=>blocks.has(keyAt(...point))));
}

const [world,output]=process.argv.slice(2);
if (!world || !output) throw new Error('Usage: node altitude-landmarks.mjs <generated/world> <client/altitude-landmark-data.mjs>');
const base=loadBase(world);
const landmarks=sites.map(({key,...options})=>({key,boxes:geometry(base,options)}));
const encoded=gzipSync(JSON.stringify(landmarks),{level:9}).toString('base64');
writeFileSync(output,'// Generated by import/altitude-landmarks.mjs\nexport default '+JSON.stringify(encoded)+';\n');
